"""Deterministic code framework generator based on LLM-generated contracts.

Generates a complete Python code scaffold from a GISDataFlowGraph:
- Data loading code for root data nodes (Layer 0)
- Contract-based pre/post assertions for operator nodes (LLM-generated)
- TODO implementation blocks for operator nodes

The generated code structure is deterministic — no LLM involvement in scaffolding.
Assertions come from the ``contracts`` field on each DAG node (generated by the
Phase 2 contract generation LLM call in ``plan_and_scaffold``).

Structural checks (``is not None``, ``OUTPUT_DIR`` existence) are applied
automatically to every operator — they are NOT part of the contracts.
"""

from __future__ import annotations

import re
from typing import Dict, List

from Agents.tools.graph import GISDataFlowGraph, OPERATOR_TYPES, DATA_TYPES


# ---------------------------------------------------------------------------
# Variable name helpers
# ---------------------------------------------------------------------------

def _sanitize_var_name(name: str) -> str:
    """Convert a node name or filename into a valid Python variable name."""
    name = re.sub(r"\.[^.]+$", "", name)
    name = re.sub(r"[^a-zA-Z0-9_]", "_", name)
    name = re.sub(r"_+", "_", name).strip("_")
    if not name or name[0].isdigit():
        name = "_" + name
    return name.lower()


def _op_var_name(node_id: str) -> str:
    """Variable name for an operator node's output."""
    return f"{str(node_id).replace('-', '_')}_output"


def _resolve_var_names(dag: GISDataFlowGraph) -> Dict[str, str]:
    """Resolve the Python variable name for every node in the DAG.

    - Root data nodes (Layer 0): sanitized node name
    - Intermediate data nodes: inherit the producing operator's output var name
    - Operator nodes: ``node_{id}_output``
    """
    nodes = dag._data.get("nodes", [])
    edges = dag._data.get("edges", [])
    node_map: Dict[str, dict] = {n.get("id"): n for n in nodes}

    producer: Dict[str, str] = {}  # data_node_id -> operator_node_id
    for edge in edges:
        src = edge.get("source")
        tgt = edge.get("target")
        src_type = node_map.get(src, {}).get("type", "")
        tgt_type = node_map.get(tgt, {}).get("type", "")
        if src_type in OPERATOR_TYPES and tgt_type in DATA_TYPES:
            producer[tgt] = src

    var_names: Dict[str, str] = {}
    for node in nodes:
        nid = node.get("id")
        ntype = node.get("type", "")
        if ntype in DATA_TYPES:
            if nid in producer:
                var_names[nid] = _op_var_name(producer[nid])
            else:
                var_names[nid] = _sanitize_var_name(node.get("name", nid))
        elif ntype in OPERATOR_TYPES:
            var_names[nid] = _op_var_name(nid)

    return var_names


# ---------------------------------------------------------------------------
# Input binding helpers
# ---------------------------------------------------------------------------

def _incoming_bindings(
    dag: GISDataFlowGraph,
    node_id: str,
    var_names: Dict[str, str],
) -> List[tuple]:
    """Return [(type_label, source_var), ...] for data inputs feeding an operator."""
    nodes = dag._data.get("nodes", [])
    edges = dag._data.get("edges", [])
    node_map: Dict[str, dict] = {n.get("id"): n for n in nodes}

    # Group by type for disambiguation
    type_counts: Dict[str, int] = {}
    bindings: List[tuple] = []
    for edge in edges:
        if edge.get("target") != node_id:
            continue
        src = edge.get("source")
        src_type = node_map.get(src, {}).get("type", "")
        if src_type not in DATA_TYPES:
            continue
        src_var = var_names.get(src, str(src))
        idx = type_counts.get(src_type, 0)
        type_counts[src_type] = idx + 1
        # Type-based label: "vector_0", "vector_1", "raster_0", etc.
        label = f"{src_type}_{idx}"
        bindings.append((label, src_var))
    return bindings


# ---------------------------------------------------------------------------
# Code block generators
# ---------------------------------------------------------------------------

def _generate_data_load_block(node: dict, var_name: str) -> List[str]:
    """Generate a TODO data-loading block with basic sanity assertions."""
    lines: List[str] = []
    nid = node.get("id")
    name = node.get("name", nid)
    ntype = node.get("type", "")
    label = f"[{nid}]"

    lines.append(f"# {nid}: {name} ({ntype})")
    lines.append(f"# TODO: load from {{DATA_DIR}}/{name}  ->  {var_name}")
    # Data contract fields as hint comment (CRS / geom_type / schema / etc.)
    hint_parts: List[str] = []
    if node.get("crs"):
        hint_parts.append(f'crs={node["crs"]}')
    if node.get("geom_type"):
        hint_parts.append(f'geom={node["geom_type"]}')
    if node.get("schema_fields"):
        hint_parts.append(f'fields={node["schema_fields"]}')
    if node.get("resolution"):
        hint_parts.append(f'resolution={node["resolution"]}')
    if node.get("bands"):
        hint_parts.append(f'bands={node["bands"]}')
    if node.get("dimensions"):
        hint_parts.append(f'dims={node["dimensions"]}')
    if node.get("variables"):
        hint_parts.append(f'vars={node["variables"]}')
    if node.get("spatial_keys"):
        hint_parts.append(f'spatial_keys={node["spatial_keys"]}')
    if hint_parts:
        lines.append(f"#   " + ", ".join(hint_parts))
    lines.append(f"{var_name} = None  # REPLACE with actual loading code")
    lines.append("")
    lines.append(f"# --- assertions ({label}) — auto-generated, verify against actual data ---")
    lines.append(f'assert {var_name} is not None, "{label}: failed to load"')
    # lines.append(f'assert not {var_name}.empty, "{label}: empty dataset"')
    contracts = node.get("contracts", {}) or {}
    for assertion in contracts.get("post", []):
        lines.append(assertion)
    lines.append("")
    return lines


def _generate_operator_block(
    dag: GISDataFlowGraph,
    node: dict,
    var_names: Dict[str, str],
    output_dir: str,
) -> List[str]:
    """Generate a TODO implementation block with contract-based assertions.

    Pre-conditions: from node.contracts["pre"] (LLM-generated)
    Post-conditions: from node.contracts["post"] (LLM-generated)
    + structural checks (is not None, OUTPUT_DIR) applied automatically
    """
    lines: List[str] = []
    nid = node.get("id")
    name = node.get("name", nid)
    ntype = node.get("type", "")
    out_var = _op_var_name(nid)
    tag = node.get("tag", "")
    func_desc = node.get("function_description", "")

    # Header with tag
    header = f"# {nid}: {name} ({ntype})"
    if tag:
        header += f"  tag: {tag}"
    lines.append(header)
    if func_desc:
        lines.append(f"# {func_desc}")

    # Input bindings comment
    bindings = _incoming_bindings(dag, nid, var_names)
    if bindings:
        arglist = ", ".join(f"{label}={var}" for label, var in bindings)
        lines.append(f"# inputs: {arglist}")

    # ── Pre-conditions (from LLM-generated contracts) ──
    contracts = node.get("contracts", {}) or {}
    pre_conditions = contracts.get("pre", [])

    if pre_conditions:
        lines.append("")
        lines.append("# Pre-conditions")
        lines.extend(pre_conditions)

    lines.append("")
    lines.append(f"# TODO: implement and assign the result to: {out_var}")
    lines.append(f"# Save any intermediate output to: {output_dir}/")
    lines.append(f"{out_var} = None  # REPLACE with actual implementation")
    lines.append("")

    # ── Post-conditions (from LLM-generated contracts + structural checks) ──
    post_conditions = contracts.get("post", [])
    out_var = _op_var_name(nid)
    label = f"[{nid}/post]"

    # Structural checks applied to every operator
    structural: List[str] = []
    if ntype == "visualization":
        structural.append(
            f'assert os.path.isdir(OUTPUT_DIR) and os.listdir(OUTPUT_DIR), '
            f'"{label}: no figure written to OUTPUT_DIR"'
        )
    else:
        structural.append(f'assert {out_var} is not None, "{label}: output is None"')

    # Final nodes (no outgoing edges): verify OUTPUT_DIR exists
    has_outgoing = any(e.get("source") == nid for e in dag._data.get("edges", []))
    if not has_outgoing and ntype != "visualization":
        structural.append(f'assert os.path.isdir(OUTPUT_DIR), "{label}: OUTPUT_DIR missing"')

    all_post = post_conditions + structural
    if all_post:
        lines.append("# Post-conditions")
        lines.extend(all_post)
        lines.append("")

    return lines


# ---------------------------------------------------------------------------
# Main scaffold function
# ---------------------------------------------------------------------------

def scaffold_code(
    dag: GISDataFlowGraph,
    data_dir: str,
    output_dir: str,
) -> str:
    """Generate a complete Python code framework from a DAG.

    Traverses the DAG in topological order and generates:
    - Data loading code for root data nodes (Layer 0)
    - Operator implementation blocks with pre/post assertions
    - Output verification for final nodes

    Intermediate data nodes (outputs of operators) are skipped — they are
    represented by the producing operator's output variable.

    Args:
        dag: The active GISDataFlowGraph.
        data_dir: Absolute path to the input data directory.
        output_dir: Absolute path to the output/workspace directory.

    Returns:
        A complete Python code string ready to be filled in by Code Generator.
    """
    nodes = dag._data.get("nodes", [])
    node_map: Dict[str, dict] = {n.get("id"): n for n in nodes}

    var_names = _resolve_var_names(dag)

    try:
        layers = dag.topological_sort()
    except ValueError as e:
        raise ValueError(f"Cannot scaffold: DAG has cycles — {e}")

    root_data_ids: set = set(
        nid for nid in layers[0]
        if node_map.get(nid, {}).get("type") in DATA_TYPES
    )
    operator_ids: set = set(
        n.get("id") for n in nodes
        if n.get("type") in OPERATOR_TYPES
    )

    lines: List[str] = []

    # Header
    lines.append("# -*- coding: utf-8 -*-")
    lines.append('"""Auto-generated code framework with embedded contracts."""')
    lines.append("import os")
    lines.append("")
    lines.append("# TODO: Add imports based on the data types and operations in this task")
    lines.append("# Vector data:  import geopandas as gpd")
    lines.append("# Tabular data: import pandas as pd")
    lines.append("# Raster data:  import rasterio")
    lines.append("# NetCDF data:  import xarray")
    lines.append("# Math/ML:      import numpy as np, scipy, sklearn")
    lines.append("# Visualization: import matplotlib; matplotlib.use('Agg'); import matplotlib.pyplot as plt")
    lines.append("# ═══ Directories ═══")
    lines.append(f'DATA_DIR = r"{data_dir}"')
    lines.append(f'OUTPUT_DIR = r"{output_dir}"')
    lines.append('os.makedirs(OUTPUT_DIR, exist_ok=True)')
    lines.append("")

    for depth, layer_ids in enumerate(layers):
        # Only emit a layer header if this layer has nodes we actually render
        # (root data or operators — intermediate data nodes are skipped).
        rendered = False
        for nid in sorted(layer_ids):
            if nid in root_data_ids or nid in operator_ids:
                if not rendered:
                    lines.append(f"# ═══ Layer {depth} ═══")
                    lines.append("")
                    rendered = True
                node = node_map.get(nid, {})
                if nid in root_data_ids:
                    lines.extend(_generate_data_load_block(node, var_names[nid]))
                else:
                    lines.extend(_generate_operator_block(dag, node, var_names, output_dir))

    # Footer
    lines.append("# ═══ Final output ═══")
    lines.append(f'print(f"Analysis complete. Results saved to {{OUTPUT_DIR}}/")')
    lines.append("")

    return "\n".join(lines)
